# Tuple creation and access

t = (10, 20, 30, 40, 50)

print(t)                 # (10, 20, 30, 40, 50)
print(type(t))           # <class 'tuple'>
print(len(t))            # 5
print(t[0])              # 10
print(t[-1])             # 50

# Single element tuple
single = (5,)
print(single)            # (5,)
print(type(single))      # <class 'tuple'>
