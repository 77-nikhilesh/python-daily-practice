"""
Problem:
A billing system needs to calculate different arithmetic results for two numbers to generate reports.

"""

a = 25
b = 4

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Exponentiation:", a ** b)

# Output:
# Addition: 29
# Subtraction: 21
# Multiplication: 100
# Division: 6.25
# Floor Division: 6
# Modulus: 1
# Exponentiation: 390625
