"""
Problem: A student evaluation system compares marks using all relational operators to determine academic performance.

"""

marks_obtained = 72
passing_marks = 40

print("Equal to:", marks_obtained == passing_marks)
print("Not Equal to:", marks_obtained != passing_marks)
print("Greater than:", marks_obtained > passing_marks)
print("Less than:", marks_obtained < passing_marks)
print("Greater than or Equal to:", marks_obtained >= passing_marks)
print("Less than or Equal to:", marks_obtained <= passing_marks)

# Output:
# Equal to: False
# Not Equal to: True
# Greater than: True
# Less than: False
# Greater than or Equal to: True
# Less than or Equal to: False
