# 1. Check if string is alphabet
print("Python".isalpha())
# Output: True

# 2. Check if string is numeric
print("12345".isdigit())
# Output: True

# 3. Check alphanumeric
print("Python3".isalnum())
# Output: True

# 4. Check lowercase
print("hello".islower())
# Output: True

# 5. Check uppercase
print("HELLO".isupper())
# Output: True

# 6. Check title case
print("Hello World".istitle())
# Output: True
