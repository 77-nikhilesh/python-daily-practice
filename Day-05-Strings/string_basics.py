# 1. Print a string
text = "Hello Python"
print(text)
# Output: Hello Python

# 2. Length of string
print(len(text))
# Output: 12

# 3. Access first and last character
print(text[0], text[-1])
# Output: H n

# 4. Concatenate strings
a = "Hello"
b = "World"
print(a + " " + b)
# Output: Hello World

# 5. Repeat string
print("Python " * 3)
# Output: Python Python Python
