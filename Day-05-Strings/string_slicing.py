text = "Programming"

# 1. Slice from index 0 to 6
print(text[0:6])
# Output: Progra

# 2. Slice from index 3 to end
print(text[3:])
# Output: gramming

# 3. Negative slicing
print(text[-5:])
# Output: ming

# 4. Reverse string
print(text[::-1])
# Output: gnimmargorP

# 5. Slice with step
print(text[::2])
# Output: Pormig

# 6. Middle characters
print(text[3:8])
# Output: gramm
