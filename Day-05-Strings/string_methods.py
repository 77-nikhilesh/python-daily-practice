# 1. Convert to uppercase
print("python".upper())
# Output: PYTHON

# 2. Convert to lowercase
print("HELLO".lower())
# Output: hello

# 3. Capitalize string
print("python developer".capitalize())
# Output: Python developer

# 4. Count character occurrences
print("banana".count("a"))
# Output: 3

# 5. Replace substring
print("I love Java".replace("Java", "Python"))
# Output: I love Python

# 6. Check startswith
print("python".startswith("py"))
# Output: True

# 7. Strip spaces
print("  hello  ".strip())
# Output: hello
